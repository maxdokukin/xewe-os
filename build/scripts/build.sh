#!/usr/bin/env bash
set -euo pipefail

# build.sh — Orchestrates compile → optional upload → optional serial monitor for ESP32.
#
# Key guarantees:
#   - ALL paths and config are computed here and passed to sub-scripts
#   - Port is optional; if omitted, we only compile
#   - Version is incremented (state committed) ONLY if upload succeeds
#   - build_info.h is generated BEFORE compilation so sources can embed it
#
# Usage examples:
#   ./build.sh -t c3
#   ./build.sh -t c3 --pin-range 1-10  <-- BATCH MODE
#   ./build.sh -t s3 -p /dev/cu.usbmodem11143201 -b 921600 -l ../lib
#
# Flags:
#   -t, --type         c3|c6|s3            (required)
#   -p, --port         Serial port (optional; if omitted -> compile only)
#   -l, --libs         Path to extra libraries folder (optional)
#   -b, --baud         Upload baud (default: 921600)
#       --venv         Path to python venv for esptool (default: build/tools/venv if exists)
#       --name         Project name override (default: repo folder name)
#       --manifest     Manifest product name (default: XeWe-LedOS)
#       --fqbn-extra   Extra Arduino FQBN opts, e.g. "FlashMode=qio,FlashFreq=80"
#       --no-monitor   Do not open serial monitor after upload
#       --compile-only Compile only (alias for omitting -p)
#       --pin-range    Range of pins to compile batch (e.g. "1-10")
#   -h, --help

#!/usr/bin/env bash
set -euo pipefail

# build.sh — Orchestrates compile → optional upload → optional serial monitor for ESP32.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

usage() {
  echo "Usage: $0 -t <c3|c6|s3> [options]"
  echo "Flags:"
  echo "  -t, --type         c3|c6|s3            (required)"
  echo "  -p, --port         Serial port (optional; if omitted -> compile only)"
  echo "      --fqbn-extra   Extra Arduino FQBN opts, e.g. \"FlashMode=qio,FlashFreq=80\""
  echo "  -h, --help         Show this help"
  exit 0
}

# ---------- Parse Args ----------
ESP_CHIP=""
ESP_PORT=""
FQBN_EXTRA_OPTS=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    -t|--type)       ESP_CHIP="$2"; shift 2 ;;
    -p|--port)       ESP_PORT="$2"; shift 2 ;;
    --fqbn-extra)    FQBN_EXTRA_OPTS="$2"; shift 2 ;;
    -h|--help)       usage ;;
    *) echo "Unknown arg: $1"; usage ;;
  esac
done

# Validate requirements
[[ ! "$ESP_CHIP" =~ ^(c3|c6|s3)$ ]] && { echo "❌ Missing/Invalid -t|--type (c3|c6|s3)"; exit 1; }

# ---------- Hardcoded Configuration ----------
VENV_DIR="${SCRIPT_DIR}/../.venv"
PROJECT_NAME="$(basename "${PROJECT_ROOT}")"
ESP_BAUD="921600"
SERIAL_BAUD="9600"

[[ ! -x "${VENV_DIR}/bin/python" ]] && { echo "❌ Venv missing at ${VENV_DIR}. Run setup script."; exit 1; }

# ---------- Paths & Initialization ----------
BUILDS_DIR="${PROJECT_ROOT}/build/builds"
WORK_DIR="${BUILDS_DIR}/cache"
STATE_FILE="${PROJECT_ROOT}/.version_state"

mkdir -p "${BUILDS_DIR}" "${WORK_DIR}"

# ---------- Helpers ----------
read_kv() { grep -E "^$1=" "$2" | cut -d'=' -f2- || true; }
write_kv() { grep -qE "^$1=" "$2" && sed -i.bak -E "s|^$1=.*|$1=$2|" "$2" && rm -f "$2.bak" || echo "$1=$2" >> "$2"; }

# ---------- State & Versioning ----------
[[ ! -f "$STATE_FILE" ]] && printf "MAJOR=0\nMINOR=0\nPATCH=0\nBUILD_ID=0\nLAST_BUILD_TS=\nPROJECT=%s\n" "$PROJECT_NAME" > "$STATE_FILE"

PATCH=$(read_kv PATCH "$STATE_FILE")
VERSION_NEXT="$(read_kv MAJOR "$STATE_FILE").$(read_kv MINOR "$STATE_FILE").$(printf "%03d" "$((10#$PATCH + 1))")"
TS_SHORT=$(date +"%Y%m%d-%H%M%S")
TS_ISO=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
CHIP_FAMILY="ESP32-$(echo "$ESP_CHIP" | tr '[:lower:]' '[:upper:]')"

read -rp "✍️  Build notes (Enter to skip): " BUILD_NOTES || true

BUILD_INFO_H="${PROJECT_ROOT}/src/build_info.h"
mkdir -p "$(dirname "${BUILD_INFO_H}")"
printf "#pragma once\n// Auto-generated by build.sh\n#define BUILD_VERSION %s\n#define BUILD_TIMESTAMP %s\n" "$VERSION_NEXT" "$TS_ISO" > "$BUILD_INFO_H"

# ---------- Compile Execution ----------
TARGET_DIR="${BUILDS_DIR}/${TS_SHORT}-${VERSION_NEXT}-${CHIP_FAMILY}-${PROJECT_NAME}"

echo "🧱 Compile → $(basename "$TARGET_DIR")"
./compile.sh -t "$ESP_CHIP" --project-root "$PROJECT_ROOT" --work-dir "$WORK_DIR" --target-dir "$TARGET_DIR" --project-name "$PROJECT_NAME" --version "$VERSION_NEXT" --timestamp "$TS_ISO" ${FQBN_EXTRA_OPTS:+--fqbn-extra "$FQBN_EXTRA_OPTS"}

[[ -n "${BUILD_NOTES//[[:space:]]/}" ]] && echo "$BUILD_NOTES" > "$TARGET_DIR/build_notes.txt"
ln -sfn "$TARGET_DIR" "${BUILDS_DIR}/latest"

# ---------- Upload Execution ----------
if [[ -n "$ESP_PORT" ]]; then
  echo "📤 Upload → $ESP_PORT @ $ESP_BAUD"
  ./upload.sh -t "$ESP_CHIP" -p "$ESP_PORT" -b "$ESP_BAUD" --build-dir "$TARGET_DIR" --venv "$VENV_DIR" || { echo "❌ Upload failed"; exit 1; }

  write_kv "$STATE_FILE" PATCH "$(printf "%03d" "$((10#$PATCH + 1))")"
  write_kv "$STATE_FILE" BUILD_ID "$((10#$(read_kv BUILD_ID "$STATE_FILE") + 1))"
  write_kv "$STATE_FILE" LAST_BUILD_TS "$TS_SHORT"
  write_kv "$STATE_FILE" PROJECT "$PROJECT_NAME"
  echo "✅ Version committed → $VERSION_NEXT"

  "${SCRIPT_DIR}/push_to_git.sh" --project-root "$PROJECT_ROOT" --target-dir "$TARGET_DIR" --version "$VERSION_NEXT"

  echo "🖥️  Serial monitor..."
  ./listen_serial.sh -p "$ESP_PORT" -b "$SERIAL_BAUD"
else
  echo "ℹ️  No port provided. Upload skipped."
fi
echo -e "\n✅ Done."