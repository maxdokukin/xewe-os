#!/usr/bin/env bash
set -euo pipefail

# build.sh — Orchestrates compile → optional upload → optional serial monitor for ESP32.
#
# Key guarantees:
#   - ALL paths and config are computed here and passed to sub-scripts
#   - Port is optional; if omitted, we only compile
#   - Version is incremented (state committed) ONLY if upload succeeds
#   - build_info.h is generated BEFORE compilation so sources can embed it
#
# Usage examples:
#   ./build.sh -c c3
#   ./build.sh -c s3 -p /dev/cu.usbmodem11143201
#
# Flags:
#   -c, --chip         c3|c6|s3            (required)
#   -p, --port         Serial port (optional; if omitted -> compile only)
# Optional flags:
# --config_json <JSON string> (additional params replaced in Config.h)

CONFIG_FILE="/Users/max/Codebase/github/xewe-os/build/build_config"
source "${CONFIG_FILE}"

PROJECT_ROOT="$(get_cfg project_root)"
PROJECT_NAME="$(get_cfg project_name)"
STATE_FILE="$(get_cfg state_file)"
ESP_CHIP=""
ESP_PORT=""
ESP_BAUD="921600"
SERIAL_BAUD="115200"

while [[ $# -gt 0 ]]; do
  case "$1" in
    -t|--type)       ESP_CHIP="$2"; shift 2 ;;
    -p|--port)       ESP_PORT="$2"; shift 2 ;;
    *) echo "Unknown arg: $1"; usage ;;
  esac
done

[[ ! "$ESP_CHIP" =~ ^(c3|c6|s3)$ ]] && { echo "❌ Missing/Invalid -t|--type (c3|c6|s3)"; exit 1; }

# ---------- Helpers ----------
read_kv() { grep -E "^$1=" "$2" | cut -d'=' -f2- || true; }
write_kv() { grep -qE "^$1=" "$2" && sed -i.bak -E "s|^$1=.*|$1=$2|" "$2" && rm -f "$2.bak" || echo "$1=$2" >> "$2"; }

[[ ! -f "$STATE_FILE" ]] && printf "MAJOR=0\nMINOR=0\nPATCH=0\nBUILD_ID=0\nLAST_BUILD_TS=\nPROJECT=%s\n" "$PROJECT_NAME" > "$STATE_FILE"

PATCH=$(read_kv PATCH "$STATE_FILE")
VERSION_NEXT="$(read_kv MAJOR "$STATE_FILE").$(read_kv MINOR "$STATE_FILE").$(printf "%03d" "$((10#$PATCH + 1))")"
TS_SHORT=$(date +"%Y%m%d-%H%M%S")
TS_ISO=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
CHIP_FAMILY="ESP32-$(echo "$ESP_CHIP" | tr '[:lower:]' '[:upper:]')"

read -rp "✍️  Build notes (Enter to skip): " BUILD_NOTES || true

BUILD_INFO_H="${PROJECT_ROOT}/src/build_info.h"
mkdir -p "$(dirname "${BUILD_INFO_H}")"
printf "#pragma once\n// Auto-generated by build.sh\n#define BUILD_VERSION %s\n#define BUILD_TIMESTAMP %s\n" "$VERSION_NEXT" "$TS_ISO" > "$BUILD_INFO_H"

./compile.sh --chip "$ESP_CHIP" --version "$VERSION_NEXT" --timestamp "$TS_ISO" ${FQBN_EXTRA_OPTS:+--fqbn-extra "$FQBN_EXTRA_OPTS"} --config_json "{\"a\": \"b\""}

[[ -n "${BUILD_NOTES//[[:space:]]/}" ]] && echo "$BUILD_NOTES" > "$TARGET_DIR/build_notes.txt"
ln -sfn "$TARGET_DIR" "${BUILDS_DIR}/latest"

# ---------- Upload Execution ----------
if [[ -n "$ESP_PORT" ]]; then
  echo "📤 Upload → $ESP_PORT @ $ESP_BAUD"
  ./upload.sh -t "$ESP_CHIP" -p "$ESP_PORT" -b "$ESP_BAUD"

  write_kv "$STATE_FILE" PATCH "$(printf "%03d" "$((10#$PATCH + 1))")"
  write_kv "$STATE_FILE" BUILD_ID "$((10#$(read_kv BUILD_ID "$STATE_FILE") + 1))"
  write_kv "$STATE_FILE" LAST_BUILD_TS "$TS_SHORT"
  write_kv "$STATE_FILE" PROJECT "$PROJECT_NAME"
  echo "✅ Version bumped → $VERSION_NEXT"

  echo "🖥️  Serial monitor..."
  ./listen_serial.sh -p "$ESP_PORT" -b "$SERIAL_BAUD"
else
  echo "ℹ️  No port provided. Upload skipped."
fi
echo -e "\n✅ Done."